// One-off extractor: reads the mirrored product pages and writes src/data/products.ts.
// Usage: node tools/extract-products.mjs <mirror-site-dir>
import fs from "node:fs";
import path from "node:path";
import { parse } from "node-html-parser";

const siteDir = process.argv[2];
if (!siteDir) throw new Error("pass the mirrored site directory");

// Homepage order (also the catalog order).
const SLUGS = [
  "latte-lover", "strawberry-matcha", "watermelon-wifey", "its-giving-guava", "berry-baddie",
  "mango-mamacita", "peach-perfection", "she-ate-strawberry", "glow-up-grape",
];

const home = parse(fs.readFileSync(path.join(siteDir, "index.html"), "utf8"));
const homeCards = home.querySelectorAll(".op-card");
const catalog = parse(fs.readFileSync(path.join(siteDir, "products/index.html"), "utf8"));
const catalogCards = catalog.querySelectorAll(".product-card");

const text = (el) => (el ? el.text.replace(/\s+/g, " ").trim() : "");
const decode = (s) => parse(`<p>${s}</p>`).text;

const products = SLUGS.map((slug, i) => {
  const doc = parse(fs.readFileSync(path.join(siteDir, "products", slug + ".html"), "utf8"));
  const card = homeCards[i];
  const cat = catalogCards[i];
  const video = card.querySelector("video");
  const catImg = cat.querySelector("img");
  const images = doc.querySelectorAll(".pd-hero__media img").map((img) => ({
    src: img.getAttribute("src"),
    className: img.getAttribute("class") || "",
    width: Number(img.getAttribute("width")),
    height: Number(img.getAttribute("height")),
    alt: decode(img.getAttribute("alt") || ""),
  }));
  const specs = doc.querySelectorAll(".pd-specs__cell").map((c) => ({
    label: text(c.querySelector("dt")),
    value: text(c.querySelector("dd")),
  }));
  const faq = doc.querySelectorAll(".pd-faq__item").map((it) => ({
    q: text(it.querySelector("dt")),
    a: it.querySelector("dd").innerHTML.trim(),
  }));
  const hasHomeNoSnippet = card.querySelector(".op-card__shell").hasAttribute("data-nosnippet");
  return {
    slug,
    key: card.getAttribute("data-product"),
    name: text(doc.querySelector(".pd-hero__copy h1")),
    type: text(card.querySelector(".op-card__eyebrow")),
    vibe: text(card.querySelector(".op-card__vibe")),
    moods: doc.querySelectorAll(".pd-moods__pill").map(text),
    homeMoods: text(card.querySelector(".op-card__moods")),
    video: video.getAttribute("data-src"),
    poster: video.getAttribute("data-poster"),
    thumb: catImg.getAttribute("src"),
    catalogPaper: cat.querySelector(".product-card__media--paper") != null,
    catalogAlt: decode(catImg.getAttribute("alt") || ""),
    homeNoSnippet: hasHomeNoSnippet,
    caption: text(doc.querySelector(".pd-hero__copy .caption")),
    description: text(doc.querySelector(".pd-hero__body")),
    images,
    specs,
    faq,
    title: text(doc.querySelector("title")),
    metaDescription: doc.querySelector('meta[name="description"]').getAttribute("content"),
  };
});

const out = `// Generated by tools/extract-products.mjs from the mirrored gimmemwah.com product pages.
export type ProductType = "SATIVA" | "HYBRID" | "INDICA";

export interface ProductImage { src: string; className: string; width: number; height: number; alt: string; }
export interface Product {
  slug: string;
  key: string;
  name: string;
  type: ProductType;
  vibe: string;
  moods: string[];
  homeMoods: string;
  video: string;
  poster: string;
  thumb: string;
  catalogPaper: boolean;
  catalogAlt: string;
  homeNoSnippet: boolean;
  caption: string;
  description: string;
  images: ProductImage[];
  specs: { label: string; value: string }[];
  /** Answer is trusted HTML copied from the source page (may contain links). */
  faq: { q: string; a: string }[];
  title: string;
  metaDescription: string;
}

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};

export function productBySlug(slug: string | undefined): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}
`;
fs.mkdirSync("src/data", { recursive: true });
fs.writeFileSync("src/data/products.ts", out);
console.log(products.map((p) => `${p.slug}: ${p.images.length} imgs, ${p.faq.length} faq, ${p.name} (${p.type})`).join("\n"));
